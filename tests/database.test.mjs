import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('PostgreSQL RLS: visitors read; only current shop admins manage products and media',async()=>{
 const db=new PGlite();
 const admin='11111111-1111-4111-8111-111111111111';
 const visitor='22222222-2222-4222-8222-222222222222';
 await db.exec(`create role anon nologin;create role authenticated nologin;
 create schema auth;create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth to anon,authenticated;
 insert into auth.users values('${admin}'),('${visitor}');
 create schema storage;create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);
 alter table storage.objects enable row level security;
 grant usage on schema storage to anon,authenticated;
 grant select,insert,update,delete on storage.objects to anon,authenticated;`);
 await db.exec(await readFile(new URL('../database/schema.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../database/storage.sql',import.meta.url),'utf8'));
 await db.exec(`insert into private.shop_admins(user_id)values('${admin}');
 insert into public.products(sku,title,category,supply,size_mm,price_vnd,thumbnail_url,is_published)values
 ('v01','Vòng xanh','vong','stock','54',1000000,'https://example.com/a.jpg',true),
 ('m01','Mặt dây','mat_day','sold',null,800000,'https://example.com/b.jpg',true),
 ('hidden','Chưa công bố','nhan','order','18,4',900000,'https://example.com/c.jpg',false);`);
 const identity=async(role,id='')=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role '+role);};
 await identity('anon');
 assert.equal((await db.query('select * from public.products')).rows.length,2);
 assert.equal((await db.query('select public.is_shop_admin() as yes')).rows[0].yes,false);
 await assert.rejects(db.exec("insert into public.products(sku,title,category,size_mm,price_vnd,thumbnail_url)values('bad','x','vong','54',1,'https://example.com/x')"),/permission denied/);
 await assert.rejects(db.exec("update public.products set supply='sold'"),/permission denied/);
 await assert.rejects(db.exec('delete from public.products'),/permission denied/);
 await assert.rejects(db.exec("insert into storage.objects(bucket_id,name)values('product-media','bad.jpg')"),/row-level security/);
 await identity('authenticated',visitor);
 assert.equal((await db.query('select * from public.products')).rows.length,2);
 assert.equal((await db.query("update public.products set supply='sold' returning id")).rows.length,0);
 assert.equal((await db.query('delete from public.products returning id')).rows.length,0);
 await assert.rejects(db.exec("insert into public.products(sku,title,category,size_mm,price_vnd,thumbnail_url)values('bad','x','vong','54',1,'https://example.com/x')"),/row-level security/);
 await assert.rejects(db.exec(`insert into private.shop_admins values('${visitor}',now())`),/permission denied/);
 await assert.rejects(db.exec('select * from private.product_audit'),/permission denied/);
 await assert.rejects(db.exec("insert into storage.objects(bucket_id,name)values('product-media','bad.jpg')"),/row-level security/);
 await identity('authenticated',admin);
 assert.equal((await db.query('select * from public.products')).rows.length,3);
 assert.equal((await db.query('select public.is_shop_admin() as yes')).rows[0].yes,true);
 await db.exec("insert into public.products(sku,title,category,size_mm,price_vnd,thumbnail_url)values('n01','Nhẫn ngọc','nhan','18',1200000,'https://example.com/n.jpg')");
 const oldRow=(await db.query("select updated_at,created_at from public.products where sku='v01'")).rows[0];
 const previous=oldRow.updated_at;
 const changed=(await db.query("update public.products set supply='sold',created_at='2000-01-01' where sku='v01' and updated_at=$1 returning *",[previous])).rows;
 assert.equal(changed.length,1);assert.equal(changed[0].supply,'sold');assert.equal(new Date(changed[0].created_at).getTime(),new Date(oldRow.created_at).getTime());
 assert.equal((await db.query("update public.products set supply='stock' where sku='v01' and updated_at=$1 returning id",[previous])).rows.length,0);
 await db.exec("insert into storage.objects(bucket_id,name)values('product-media','real.jpg')");
 await assert.rejects(db.exec("insert into storage.objects(bucket_id,name)values('another-bucket','bad.jpg')"),/row-level security/);
 assert.equal((await db.query('select * from storage.objects')).rows.length,1);
 await assert.rejects(db.exec("update public.products set ni_tay=null where sku='n01'"),/Use Size/);
 await assert.rejects(db.exec("update public.products set ni_tay=54 where sku='m01'"),/Use Size/);
 await assert.rejects(db.exec("update public.products set price_vnd=-1 where sku='m01'"),/check constraint/);
 await assert.rejects(db.exec("update public.products set treatment='a' where sku='m01'"),/treatment_evidence/);
 await assert.rejects(db.exec("update public.products set gallery_urls=array['javascript:alert(1)'] where sku='m01'"),/Gallery URLs/);
 await assert.rejects(db.exec("insert into public.products(sku,title,category,size_mm,price_vnd,thumbnail_url)values('V01','duplicate','vong','54',1,'https://example.com/x')"),/unique constraint/);
 assert.equal((await db.query("delete from public.products where sku='n01' returning id")).rows.length,1);
 await db.exec('reset role');
 assert.ok((await db.query('select * from private.product_audit')).rows.length>=6);
 await db.exec(`delete from private.shop_admins where user_id='${admin}'`);
 await identity('authenticated',admin);
 assert.equal((await db.query('select public.is_shop_admin() as yes')).rows[0].yes,false);
 assert.equal((await db.query("update public.products set supply='stock' returning id")).rows.length,0);
 assert.equal((await db.query("delete from storage.objects returning id")).rows.length,0);
 await db.close();
});
